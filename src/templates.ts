export type Template = (typeof templates)[number];
export function templateDocument(t: Template) {
  const w = t.w,
    h = t.h;
  const rect = (
    left: number,
    top: number,
    width: number,
    height: number,
    fill: string,
    extra = {},
  ) => ({ type: "Rect", left, top, width, height, fill, ...extra });
  const objects: any[] = [
    rect(w * 0.65, -h * 0.08, w * 0.5, h * 1.2, t.accent, {
      angle: 15,
      rx: w * 0.2,
      ry: w * 0.2,
      opacity: 0.35,
    }),
    {
      type: "Circle",
      left: w * 0.62,
      top: h * 0.22,
      radius: w * 0.19,
      fill: t.accent,
      opacity: 0.8,
    },
    {
      type: "Textbox",
      left: w * 0.07,
      top: h * 0.08,
      width: w * 0.7,
      text: "FORMA  /  DESIGN STORIES",
      fontFamily: "Arial",
      fontSize: w * 0.018,
      fill: t.ink,
      charSpacing: 130,
    },
    {
      type: "Textbox",
      left: w * 0.07,
      top: h * 0.3,
      width: w * 0.82,
      text: t.headline,
      fontFamily:
        t.style === "botanic" || t.style === "coffee" ? "Georgia" : "Arial",
      fontSize: w * 0.11,
      fontWeight: t.style === "botanic" ? "normal" : "bold",
      lineHeight: 0.95,
      fill: t.ink,
    },
    {
      type: "Textbox",
      left: w * 0.075,
      top: h * 0.85,
      width: w * 0.82,
      text: t.sub,
      fontFamily: "Arial",
      fontSize: w * 0.019,
      charSpacing: 60,
      fill: t.ink,
    },
    rect(w * 0.075, h * 0.8, w * 0.1, 3, t.ink),
  ];
  return {
    pages: [
      { id: uid(), canvas: { version: "6.7.1", background: t.bg, objects } },
    ],
  };
}
