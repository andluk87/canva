import { test, expect } from "@playwright/test";
import { totpCode } from "../../server/accounts.mjs";
const unique = () => `accounts-${Date.now()}-${Math.random().toString(16).slice(2)}@example.test`;
const password = "account-current-2026";

test("accounts: profile and password changes persist; another session is revoked", async ({ page, browser }) => {
  const email = unique();
  await page.request.post("/api/auth/register", { data: { name: "Before Designer", email, password } });
  const other = await browser.newContext();
  await other.request.post("/api/auth/login", { data: { email, password } });
  await page.goto("/");
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Настройки аккаунта" })).toBeVisible();
  await page.getByLabel("Имя в профиле", { exact: true }).fill("После обновления");
  await page.getByRole("button", { name: "Сохранить профиль", exact: true }).click();
  await expect(page.locator(".workspace")).toContainText("После обновления");
  await page.reload();
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  await expect(page.getByLabel("Имя в профиле", { exact: true })).toHaveValue("После обновления");
  await expect(page.locator(".account-session")).toHaveCount(2);
  await page.getByLabel("Текущий пароль", { exact: true }).fill("wrong-password");
  await page.getByLabel("Новый пароль", { exact: true }).fill("account-updated-2026");
  await page.getByLabel("Повторите новый пароль", { exact: true }).fill("account-updated-2026");
  await page.getByRole("button", { name: "Изменить пароль", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Текущий пароль указан неверно");
  await page.getByLabel("Текущий пароль", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Изменить пароль", exact: true }).click();
  await expect(page.locator(".account-session")).toHaveCount(1);
  expect((await other.request.get("/api/auth/me")).status()).toBe(401);
  expect((await page.request.get("/api/auth/me")).status()).toBe(200);
  expect((await other.request.post("/api/auth/login", { data: { email, password } })).status()).toBe(401);
  expect((await other.request.post("/api/auth/login", { data: { email, password: "account-updated-2026" } })).status()).toBe(200);
  await page.getByRole("button", { name: "Выйти на всех устройствах", exact: true }).click();
  await page.getByRole("button", { name: "Выйти везде", exact: true }).click();
  await expect(page.locator(".workspace")).toContainText("Личное пространство");
  expect((await other.request.get("/api/auth/me")).status()).toBe(401);
  await other.close();
});

test("accounts: actual TOTP setup, recovery download and login challenge", async ({ page, browser }) => {
  const email = unique();
  await page.request.post("/api/auth/register", { data: { name: "Protected Designer", email, password } });
  await page.goto("/");
  await page.getByRole("button", { name: "Настройки", exact: true }).click();
  await page.getByLabel("Пароль для управления защитой", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Настроить защиту", exact: true }).click();
  const secret = (await page.getByLabel("Ключ аутентификатора", { exact: true }).innerText()).trim();
  expect(secret).toMatch(/^[A-Z2-7]{32}$/);
  await page.getByLabel("Код аутентификатора или резервный код", { exact: true }).fill(totpCode(secret));
  await page.getByRole("button", { name: "Подтвердить подключение", exact: true }).click();
  const recovery = page.getByRole("region", { name: "Резервные коды" });
  await expect(recovery).toBeVisible();
  await expect(recovery.locator("code")).toHaveCount(10);
  const code = await recovery.locator("code").first().innerText();
  const download = page.waitForEvent("download");
  await recovery.getByRole("button", { name: "Скачать коды", exact: true }).click();
  expect((await download).suggestedFilename()).toBe("forma-recovery-codes.txt");
  await recovery.getByLabel("Я сохранил резервные коды", { exact: true }).check();
  await recovery.getByRole("button", { name: "Готово", exact: true }).click();
  await expect(page.locator(".account-status.enabled")).toContainText("Включена");
  const fresh = await browser.newContext();
  const login = await fresh.newPage();
  await login.goto("/");
  await login.getByRole("button", { name: "Создать дизайн", exact: true }).click();
  const dialog = login.getByRole("dialog");
  await dialog.getByRole("button", { name: "Уже есть аккаунт? Войти", exact: true }).click();
  await dialog.getByLabel("Email", { exact: true }).fill(email);
  await dialog.getByLabel("Пароль", { exact: true }).fill(password);
  await dialog.getByRole("button", { name: "Войти", exact: true }).click();
  await expect(dialog).toContainText("Введите код");
  await dialog.getByLabel("Код двухфакторной защиты", { exact: true }).fill(code);
  await dialog.getByRole("button", { name: "Войти", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(login.locator(".workspace")).toContainText("Protected Designer");
  expect((await fresh.request.post("/api/auth/login", { data: { email, password, twoFactorCode: code } })).status()).toBe(401);
  await fresh.close();
});
